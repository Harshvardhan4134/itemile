/**
 * Sync Firebase web config from .env → public/firebase-messaging-sw.js
 * Run: npm run firebase:sync-config
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

function loadEnv(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const env = {};
  for (const line of fs.readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim();
    env[key] = value;
  }
  return env;
}

const env = { ...loadEnv(path.join(root, ".env.example")), ...loadEnv(path.join(root, ".env")) };

const required = [
  "VITE_FIREBASE_API_KEY",
  "VITE_FIREBASE_AUTH_DOMAIN",
  "VITE_FIREBASE_PROJECT_ID",
  "VITE_FIREBASE_STORAGE_BUCKET",
  "VITE_FIREBASE_MESSAGING_SENDER_ID",
  "VITE_FIREBASE_APP_ID",
];

const missing = required.filter((k) => !env[k]);
if (missing.length) {
  console.warn(
    `[firebase:sync-config] Missing in .env: ${missing.join(", ")}. ` +
      "Service worker will use placeholders until you fill .env."
  );
}

const config = {
  apiKey: env.VITE_FIREBASE_API_KEY || "REPLACE_ME",
  authDomain: env.VITE_FIREBASE_AUTH_DOMAIN || "itemile-prod.firebaseapp.com",
  projectId: env.VITE_FIREBASE_PROJECT_ID || "itemile-prod",
  storageBucket: env.VITE_FIREBASE_STORAGE_BUCKET || "itemile-prod.appspot.com",
  messagingSenderId: env.VITE_FIREBASE_MESSAGING_SENDER_ID || "000000000000",
  appId: env.VITE_FIREBASE_APP_ID || "1:000000000000:web:000000000000",
};

const sw = `// Auto-generated by scripts/sync-firebase-config.mjs — do not edit by hand
importScripts('https://www.gstatic.com/firebasejs/10.14.1/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.14.1/firebase-messaging-compat.js');

firebase.initializeApp(${JSON.stringify(config, null, 2)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage((payload) => {
  const notificationTitle = payload.notification?.title || 'Itemile';
  const notificationOptions = {
    body: payload.notification?.body || '',
    icon: '/favicon.png',
  };
  self.registration.showNotification(notificationTitle, notificationOptions);
});
`;

const out = path.join(root, "public", "firebase-messaging-sw.js");
fs.writeFileSync(out, sw);
console.log(`Wrote ${out} for project: ${config.projectId}`);
